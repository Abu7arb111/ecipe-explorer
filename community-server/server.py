#!/usr/bin/env python3
"""Recipe Explorer community server.

A small, dependency-free (Python 3.9+ standard library only) REST server that lets
several copies of the Recipe Explorer app share published recipes.

    GET    /recipes          list every published recipe (newest first)
    GET    /recipes/<id>     one recipe
    POST   /recipes          publish a recipe              (author headers required)
    PUT    /recipes/<id>     edit a recipe     (author only, otherwise 403)
    DELETE /recipes/<id>     remove a recipe   (author only, otherwise 403)
    GET    /health           liveness check

Ownership: every write request carries two headers.
    X-Author-ID     the author's public UUID (stored on each of their recipes)
    X-Author-Token  a private secret generated by the app
The first time an author ID publishes, the server remembers a SHA-256 hash of its
token. After that, writes for that author must present the same token, and only
the author ID stored on a recipe may update or delete it.

This is "trust on first use", not real accounts: it stops other users from
editing your recipes, but it is not a substitute for proper sign-in, and the
server should only be exposed on a network you trust (or put behind HTTPS).

Usage:
    python3 server.py                      # http://127.0.0.1:8080, data in community-data.json
    python3 server.py --host 0.0.0.0       # reachable from a physical iPhone on the same Wi-Fi
    python3 server.py --port 9000 --data /tmp/feed.json
"""

import argparse
import hashlib
import hmac
import json
import os
import sys
import tempfile
import threading
import uuid
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

MAX_BODY_BYTES = 1_000_000
MAX_TEXT = 4_000
MAX_ITEMS = 100


class ApiError(Exception):
    def __init__(self, status, message):
        super().__init__(message)
        self.status = status
        self.message = message


def now_iso():
    # Matches Swift's JSONDecoder .iso8601 strategy (no fractional seconds).
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def normalize_uuid(value, what):
    if not isinstance(value, str):
        raise ApiError(400, f"{what} must be a UUID string.")
    try:
        return str(uuid.UUID(value)).upper()  # Swift encodes UUIDs in upper case
    except ValueError:
        raise ApiError(400, f"{what} is not a valid UUID.")


def hash_token(token):
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Validation: every recipe in the feed must decode as a Swift `Recipe`, otherwise
# one bad upload would break the feed for everybody.
# ---------------------------------------------------------------------------

def _text(body, key, required=True, allow_empty=True):
    value = body.get(key)
    if value is None and not required:
        return ""
    if not isinstance(value, str):
        raise ApiError(400, f"'{key}' must be text.")
    if len(value) > MAX_TEXT:
        raise ApiError(400, f"'{key}' is too long.")
    if not allow_empty and not value.strip():
        raise ApiError(400, f"'{key}' can't be empty.")
    return value


def _int(body, key, low, high):
    value = body.get(key)
    if isinstance(value, bool) or not isinstance(value, int) or not (low <= value <= high):
        raise ApiError(400, f"'{key}' must be a whole number from {low} to {high}.")
    return value


def _text_list(body, key, allow_empty_list=True):
    value = body.get(key)
    if not isinstance(value, list) or len(value) > MAX_ITEMS:
        raise ApiError(400, f"'{key}' must be a list of at most {MAX_ITEMS} items.")
    if not allow_empty_list and not value:
        raise ApiError(400, f"'{key}' needs at least one entry.")
    for item in value:
        if not isinstance(item, str) or len(item) > MAX_TEXT:
            raise ApiError(400, f"Every entry in '{key}' must be text.")
    return list(value)


def clean_recipe(body, recipe_id, author_id, published_at):
    """Returns a recipe containing only known, well-typed fields."""
    if not isinstance(body, dict):
        raise ApiError(400, "Request body must be a JSON object.")

    rating = body.get("rating", 0)
    if isinstance(rating, bool) or not isinstance(rating, (int, float)) or not (0 <= rating <= 5):
        raise ApiError(400, "'rating' must be a number from 0 to 5.")

    image_url = _text(body, "imageURL", required=False).strip()
    if image_url and not (image_url.lower().startswith("http://") or image_url.lower().startswith("https://")):
        raise ApiError(400, "'imageURL' must start with http:// or https://.")

    raw_ingredients = body.get("ingredients")
    if not isinstance(raw_ingredients, list) or not raw_ingredients or len(raw_ingredients) > MAX_ITEMS:
        raise ApiError(400, "'ingredients' needs between 1 and 100 entries.")
    ingredients = []
    for entry in raw_ingredients:
        if not isinstance(entry, dict):
            raise ApiError(400, "Each ingredient must be an object.")
        ingredients.append({
            "id": normalize_uuid(entry.get("id"), "Ingredient id"),
            "item": _text(entry, "item", allow_empty=False),
            "amount": _text(entry, "amount"),
        })

    instructions = _text_list(body, "instructions", allow_empty_list=False)
    if any(not step.strip() for step in instructions):
        raise ApiError(400, "Instruction steps can't be empty.")

    return {
        "id": recipe_id,
        "title": _text(body, "title", allow_empty=False).strip(),
        "description": _text(body, "description"),
        "category": _text(body, "category", allow_empty=False),
        "cuisine": _text(body, "cuisine"),
        "prepTime": _int(body, "prepTime", 0, 1440),
        "cookTime": _int(body, "cookTime", 0, 1440),
        "servings": _int(body, "servings", 1, 100),
        "difficulty": _text(body, "difficulty"),
        "rating": rating,
        "author": _text(body, "author", allow_empty=False).strip(),
        "imageURL": image_url,
        "tags": _text_list(body, "tags"),
        "ingredients": ingredients,
        "instructions": instructions,
        # Personal data (likes, the publisher's own rating/reaction) is never shared.
        "isUserCreated": True,
        "likes": 0,
        "dislikes": 0,
        "authorID": author_id,
        "publishedAt": published_at,
    }


# ---------------------------------------------------------------------------
# Storage
# ---------------------------------------------------------------------------

class CommunityStore:
    def __init__(self, path):
        self.path = path
        self.lock = threading.Lock()
        self.recipes = {}   # id -> recipe
        self.authors = {}   # authorID -> sha256(token)
        if os.path.exists(path):
            try:
                with open(path, "r", encoding="utf-8") as handle:
                    data = json.load(handle)
                self.recipes = {r["id"]: r for r in data.get("recipes", [])}
                self.authors = dict(data.get("authors", {}))
            except (OSError, ValueError, KeyError, TypeError) as error:
                sys.exit(f"Can't read {path}: {error}. Fix or move the file, then start again.")

    def _save(self):
        payload = {"recipes": list(self.recipes.values()), "authors": self.authors}
        directory = os.path.dirname(os.path.abspath(self.path))
        fd, temp_path = tempfile.mkstemp(dir=directory, prefix=".community-", suffix=".json")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, indent=2)
            os.replace(temp_path, self.path)  # atomic: never leaves a half-written file
        except BaseException:
            if os.path.exists(temp_path):
                os.remove(temp_path)
            raise

    def _verify(self, author_id, token):
        known = self.authors.get(author_id)
        if known is None:
            self.authors[author_id] = hash_token(token)  # first use registers the author
        elif not hmac.compare_digest(known, hash_token(token)):
            raise ApiError(403, "Only the recipe's author can do that.")

    def list(self):
        with self.lock:
            return sorted(self.recipes.values(), key=lambda r: r.get("publishedAt", ""), reverse=True)

    def get(self, recipe_id):
        with self.lock:
            recipe = self.recipes.get(recipe_id)
        if recipe is None:
            raise ApiError(404, "Recipe not found.")
        return recipe

    def publish(self, body, author_id, token):
        if not isinstance(body, dict):
            raise ApiError(400, "Request body must be a JSON object.")
        recipe_id = normalize_uuid(body.get("id"), "Recipe id")
        claimed = body.get("authorID")
        if claimed is not None and normalize_uuid(claimed, "authorID") != author_id:
            raise ApiError(403, "You can only publish recipes as yourself.")
        recipe = clean_recipe(body, recipe_id, author_id, now_iso())
        with self.lock:
            self._verify(author_id, token)
            if recipe_id in self.recipes:
                raise ApiError(409, "This recipe is already published.")
            self.recipes[recipe_id] = recipe
            self._save()
        return recipe

    def update(self, recipe_id, body, author_id, token):
        if isinstance(body, dict) and body.get("id") is not None:
            if normalize_uuid(body.get("id"), "Recipe id") != recipe_id:
                raise ApiError(400, "The recipe id in the body doesn't match the URL.")
        with self.lock:
            existing = self.recipes.get(recipe_id)
            if existing is None:
                raise ApiError(404, "Recipe not found.")
            if existing["authorID"] != author_id:
                raise ApiError(403, "Only the recipe's author can edit it.")
            self._verify(author_id, token)
            recipe = clean_recipe(body, recipe_id, author_id, existing["publishedAt"])
            recipe["updatedAt"] = now_iso()
            self.recipes[recipe_id] = recipe
            self._save()
        return recipe

    def delete(self, recipe_id, author_id, token):
        with self.lock:
            existing = self.recipes.get(recipe_id)
            if existing is None:
                raise ApiError(404, "Recipe not found.")
            if existing["authorID"] != author_id:
                raise ApiError(403, "Only the recipe's author can delete it.")
            self._verify(author_id, token)
            del self.recipes[recipe_id]
            self._save()


# ---------------------------------------------------------------------------
# HTTP layer
# ---------------------------------------------------------------------------

class Handler(BaseHTTPRequestHandler):
    store = None  # set in main()
    server_version = "RecipeExplorerCommunity/1.0"

    def do_GET(self):
        self._handle(lambda parts: self._get(parts))

    def do_POST(self):
        self._handle(lambda parts: self._post(parts))

    def do_PUT(self):
        self._handle(lambda parts: self._put(parts))

    def do_DELETE(self):
        self._handle(lambda parts: self._delete(parts))

    # Routing ---------------------------------------------------------------

    def _get(self, parts):
        if parts == ["health"]:
            return 200, {"status": "ok"}
        if parts == ["recipes"]:
            return 200, self.store.list()
        if len(parts) == 2 and parts[0] == "recipes":
            return 200, self.store.get(normalize_uuid(parts[1], "Recipe id"))
        raise ApiError(404, "Not found.")

    def _post(self, parts):
        if parts != ["recipes"]:
            raise ApiError(404, "Not found.")
        author_id, token = self._author()
        return 201, self.store.publish(self._json_body(), author_id, token)

    def _put(self, parts):
        if len(parts) != 2 or parts[0] != "recipes":
            raise ApiError(404, "Not found.")
        recipe_id = normalize_uuid(parts[1], "Recipe id")
        author_id, token = self._author()
        return 200, self.store.update(recipe_id, self._json_body(), author_id, token)

    def _delete(self, parts):
        if len(parts) != 2 or parts[0] != "recipes":
            raise ApiError(404, "Not found.")
        recipe_id = normalize_uuid(parts[1], "Recipe id")
        author_id, token = self._author()
        self.store.delete(recipe_id, author_id, token)
        return 204, None

    # Helpers ---------------------------------------------------------------

    def _handle(self, route):
        try:
            path = self.path.split("?", 1)[0]
            parts = [p for p in path.split("/") if p]
            status, payload = route(parts)
        except ApiError as error:
            status, payload = error.status, {"error": error.message}
        except Exception as error:  # never leak a stack trace to clients
            self.log_error("Unexpected error: %r", error)
            status, payload = 500, {"error": "Internal server error."}
        self._send(status, payload)

    def _author(self):
        raw_id = self.headers.get("X-Author-ID")
        token = self.headers.get("X-Author-Token")
        if not raw_id or not token:
            raise ApiError(401, "X-Author-ID and X-Author-Token headers are required.")
        if not (16 <= len(token) <= 256):
            raise ApiError(401, "X-Author-Token has an invalid length.")
        return normalize_uuid(raw_id, "X-Author-ID"), token

    def _json_body(self):
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            raise ApiError(400, "Invalid Content-Length.")
        if length <= 0:
            raise ApiError(400, "A JSON body is required.")
        if length > MAX_BODY_BYTES:
            raise ApiError(413, "Request body is too large.")
        try:
            return json.loads(self.rfile.read(length).decode("utf-8"))
        except (UnicodeDecodeError, ValueError):
            raise ApiError(400, "Request body isn't valid JSON.")

    def _send(self, status, payload):
        self.send_response(status)
        if payload is None:
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        body = json.dumps(payload).encode("utf-8")
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def main():
    parser = argparse.ArgumentParser(description="Recipe Explorer community server")
    parser.add_argument("--host", default="127.0.0.1",
                        help="address to listen on (use 0.0.0.0 for devices on your Wi-Fi)")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--data", default="community-data.json", help="JSON file used for storage")
    args = parser.parse_args()

    Handler.store = CommunityStore(args.data)
    server = ThreadingHTTPServer((args.host, args.port), Handler)
    print(f"Recipe Explorer community server on http://{args.host}:{args.port}  (data: {args.data})")
    print("Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
